// Deterministic, nonsemantic public retrieval exports. No private workflow bodies.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const generated = new Set(['docs/high_signal_file_index.json', 'docs/codebase-overview.md', 'llms.txt', 'llms-small.txt', 'llms-facts.txt', 'llms-full.txt']);
const privateNames = /^(?:AGENTS\.md|CLAUDE\.md|GEMINI\.md|memory\.md|prompts\.md|MCP-SERVERS-SYNC\.md|CONCEPT-FAMILY-SKILLS-OPTIMIZATION\.md|copilot-instructions\.md|\.env(?:\..*)?)$/i;
export function isPublicPath(file) {
  return !file.split('/').some(part => ['.git', '.claude', '.remember', '.vscode', 'node_modules', '__pycache__'].includes(part)) &&
    !privateNames.test(path.basename(file)) && !file.startsWith('docs/archive/') &&
    !generated.has(file) && file !== 'package-lock.json' && !file.endsWith('.log') &&
    !file.endsWith('-tech-review.md') && !file.includes('code-deep-optimizer-') && !file.includes('repo-bootstrap-audit-');
}
const purposes = {
  'proxy-a.mjs': 'Messages reverse proxy, byte replay, cache, statistics and monitoring.',
  'cli.mjs': 'Installed local controller and setup wizard.',
  'cachectl-a.sh': 'Source controller and explicit user service integration.',
  'cache-explorer.mjs': 'Local cache list, view, invalidate and terminal UI.',
  'bench.py': 'Live paid cache benchmark using response classification.',
  'lib/controller.mjs': 'Safe dotenv, HTTP probe and process ownership helpers.',
  'lib/proxy-config.mjs': 'Validated startup limits.',
  'lib/proxy-validation.mjs': 'Pure limits, pricing and normalization validators.',
  'lib/operations-registry.mjs': 'Declarative external-call inventory.',
  'test-helpers.mjs': 'Isolated local mock proxy harness.',
  'test-fidelity.mjs': 'Explicit live paid fidelity proof.',
};
export function buildOutputs() {
  const names = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { encoding: 'utf8' }).split('\0');
  const files = [...new Set(names)].filter(file => file && isPublicPath(file) && fs.existsSync(file) && fs.lstatSync(file).isFile()).sort();
  const entries = files.map(file => {
    const text = fs.readFileSync(file, 'utf8');
    const layer = /(?:\.test\.mjs|_test\.py|test-)/.test(file) ? 'test' : file.startsWith('lib/') ? 'shared' : file.startsWith('scripts/') ? 'tooling' : file.endsWith('.md') ? 'docs' : /\.(json|yml|example)$/.test(file) || file.startsWith('.') ? 'config' : 'runtime';
    const exports = [...text.matchAll(/export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)/g)].map(m => m[1]);
    for (const list of text.matchAll(/export\s*\{([^}]+)\}/g)) {
      for (const item of list[1].split(',')) {
        const name = item.trim().split(/\s+as\s+/).pop();
        if (/^\w+$/.test(name)) exports.push(name);
      }
    }
    const dependencies = [...text.matchAll(/(?:from\s+|import\s*\()['"]([^'"]+)['"]/g)].map(m => m[1]).filter(p => p.startsWith('.')).map(p => path.posix.normalize(path.posix.join(path.posix.dirname(file), p)));
    const purpose = purposes[file] || (layer === 'test' ? 'Behavior regression fixture and assertions.' : layer === 'docs' ? 'Maintained project reference.' : layer === 'tooling' ? 'Repository maintenance entrypoint.' : 'Project configuration or reference asset.');
    return { path: file, purpose, layer, exports: [...new Set(exports)], depends_on: [...new Set(dependencies)], patterns: [] };
  });
  const map = '# Codebase overview\n\nGenerated by `npm run docs:generate`. Public source/config/reference census. Private\nworkflow documents and historical machine notes are excluded at every depth.\n\n| Path | Layer | Purpose |\n|---|---|---|\n' + entries.map(e => `| [${e.path}](${path.posix.relative('docs', e.path)}) | ${e.layer} | ${e.purpose} |`).join('\n') + '\n';
  const small = '# llm-cache-proxy\n\nZero-dependency local Messages replay proxy. [src: README.md]\nValidate offline: `npm run validate`. [src: package.json]\nStart: `./cachectl-a.sh setup` then `./cachectl-a.sh on`. [src: USAGE.md]\nPaid opt-ins: `npm run test:fidelity`, `python3 bench.py`. [src: package.json; bench.py]\nRead `docs/wiki/README.md` for maintained references. [src: docs/wiki/README.md]\n';
  const links = '# llm-cache-proxy retrieval\n\n## References\n' + ['README.md', 'USAGE.md', 'docs/wiki/README.md', 'docs/ARCHITECTURE.md', 'docs/DEVELOPMENT.md', 'docs/TESTING.md', 'docs/SECURITY.md', 'docs/COMPONENTS.md', 'docs/known-issues.md', 'docs/high_signal_file_index.json'].map(p => `- [${p}](${p})`).join('\n') + '\n';
  const selected = ['README.md', 'USAGE.md', 'docs/ARCHITECTURE.md', 'docs/DEVELOPMENT.md', 'docs/TESTING.md', 'docs/SECURITY.md', 'docs/known-issues.md'];
  const full = (small + '\n' + selected.map(file => {
    let fenced = false;
    const text = fs.readFileSync(file, 'utf8').split('\n').map(line => {
      if (line.startsWith('```')) { fenced = !fenced; return line; }
      return !line || fenced ? line : `${line} [src: ${file}]`;
    }).join('\n');
    return `## Source: ${file} [src: ${file}]\n\n${text}`;
  }).join('\n\n')).trimEnd() + '\n';
  return { 'docs/high_signal_file_index.json': JSON.stringify(entries, null, 2) + '\n', 'docs/codebase-overview.md': map, 'llms.txt': links, 'llms-small.txt': small, 'llms-facts.txt': small, 'llms-full.txt': full };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [file, content] of Object.entries(buildOutputs())) fs.writeFileSync(file, content);
  console.log('Public documentation indexes generated.');
}
